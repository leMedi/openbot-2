#!/usr/bin/env bash
# Runs as root on every start, then hands over to the command (supervisord). Volumes may arrive empty or root-owned,
# so the folders' owners and modes are set here rather than at build time.
set -euo pipefail

: "${OPENBOT_DATA_DIR:?}" "${OPENBOT_HOME:?}" "${OPENBOT_APP_DIR:?}"

# Target-specific setup, e.g. the dev image's.
for hook in /etc/openbot/entrypoint.d/*.sh; do
  [[ -e "${hook}" ]] && source "${hook}"
done

# The data dir is the server's alone: 0700, so the bots' user can't read it (without sudo; see ADR 0002).
install -d -o openbot-server -g openbot-server -m 0700 "${OPENBOT_DATA_DIR}"
# The bots' world.
install -d -o openbot -g openbot -m 0755 "${OPENBOT_HOME}" "${OPENBOT_HOME}/shared" "${OPENBOT_HOME}/bots"
install -d -o openbot-server -g openbot-server -m 0755 "${OPENBOT_APP_DIR}"
# The release the image embeds, if any, unless a newer one is installed already.
openbot-install-release
# The screen daemon's socket folder, and X's (root-owned and sticky, as X expects, so each screen's Xvfb can add its own).
install -d -o openbot -g openbot -m 0755 /run/openbot
install -d -o root -g root -m 1777 /tmp/.X11-unix

# The secret key, when OPENBOT_SECRET_KEY is empty, is generated by the server into the data dir when it first starts
# (the healthcheck's first request), and kept there across restarts.

exec "$@"
